// Exact two-source provenance and focused extraction; no browser/GPU and no source mutation.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import * as tuning from '../js/euc/data/tuning.js';

const root = new URL('../', import.meta.url), read = rel => readFileSync(new URL(rel, root), 'utf8');
const manifest = JSON.parse(read('js/euc/MANIFEST.json'));
const base = '5f45fff19b258e140833841ba2473069af751a12', donor = 'd37efc07cddc0d76ff7aa585901710d357b8e5a1';
const sha = bytes => createHash('sha256').update(bytes).digest('hex');

test('only six explicitly reviewed donor files participate; all roster/audio/pixel source stays pinned to the base', () => {
  assert.equal(manifest.commit, base); assert.equal(manifest.sources.base.commit, base); assert.equal(manifest.sources.donor.commit, donor);
  assert.deepEqual(manifest.sources.donor.files.map(f => f.source).sort(), [
    'src/app/nearSolids.ts', 'src/data/tuning.ts', 'src/render/ridingRig.ts', 'src/simulation/EucController.ts',
    'src/simulation/eucStepPrimitives.ts', 'src/simulation/world.ts']);
  for (const [file, record] of Object.entries(manifest.files)) {
    assert.equal(sha(read(`js/euc/${file}`)), record.outputSha256, file);
    if (record.source) assert.equal(record.sourceCommit, file === 'app/nearSolids.js' ? donor : base);
    if (record.donor) {
      assert.equal(record.donor.commit, donor);
      assert.ok(manifest.sources.donor.files.some(f => f.source === record.donor.source && f.sourceSha256 === record.donor.sourceSha256));
    }
  }
  assert.equal(Object.keys(manifest.files).length, 101); assert.equal(manifest.eager.length, 41); assert.equal(manifest.deferred.length, 60);
  assert.ok(manifest.eager.includes('app/nearSolids.js'));
  assert.equal(manifest.roster.length, 11); assert.equal(manifest.audio.length, 18); assert.equal(manifest.shippedAudio.length, 17);
  assert.ok(manifest.workers.modules.every(file => !file.includes('nearSolids') && !file.includes('ridingRig')));
});

test('tuning imports exactly two donor declarations while the 64 base exports stay unchanged', () => {
  assert.equal(Object.keys(tuning).length, 66);
  assert.equal(tuning.SKATE_TRANSITION.wallTurnSeconds, .3);
  assert.equal(tuning.NEAR_SOLID.directions, 12);
  assert.ok(Object.isFrozen(tuning.SKATE_TRANSITION));
  assert.equal(tuning.TUNING.SKATE_TRANSITION, undefined, 'base root/aliases are preserved');
  const source = read('js/euc/data/tuning.js');
  const donorAt = source.indexOf('export const NEAR_SOLID');
  assert.ok(donorAt > 0);
  // The original generated file, including its licence banner, remains byte-for-byte below its updated header.
  const baseBody = source.slice(0, donorAt).trimEnd().replace(' + reviewed d37efc0 declarations (MANIFEST.json)', '') + '\n';
  assert.equal(sha(baseBody), '3f903c034780b71c4241ce062ee38c76be23e35d9083ed4275702d4e8e865d96');
});

const donorRoot = new URL('../EUC-thrills-latest/', root), baseRoot = new URL('../EUC-thrills/', root);
test('actual donor bytes match every recorded exact hash', { skip: !existsSync(new URL('src/app/nearSolids.ts', donorRoot)) && 'optional donor source unavailable' }, () => {
  for (const record of manifest.sources.donor.files) assert.equal(sha(readFileSync(new URL(record.source, donorRoot))), record.sourceSha256, record.source);
});

test('dual-source --check reproduces all generated bytes and rejects the wrong donor revision', {
  skip: (!existsSync(new URL('node_modules/typescript/package.json', baseRoot)) || !existsSync(new URL('.git', donorRoot))) && 'optional source/tooling checkouts unavailable',
}, () => {
  const run = args => spawnSync(process.execPath, ['tools/vendor-euc.mjs', ...args], { cwd: root, encoding: 'utf8', timeout: 20000 });
  const checked = run(['--check']);
  assert.equal(checked.status, 0, checked.stdout + checked.stderr);
  const wrong = run(['--check', '--donor', '../EUC-thrills']);
  assert.notEqual(wrong.status, 0); assert.match(wrong.stderr, /donor must be pinned/);
});
